#!/usr/bin/env python3
"""
PR Manager Module

Manages Pull Request creation and lifecycle.
"""

import os
import sys
from typing import Dict, Any, Optional, List

from .github_client import GitHubClient


class PRManager:
    """Manage pull request operations."""

    def __init__(self, github_token: Optional[str] = None):
        """Initialize PR manager."""
        self.github = GitHubClient(token=github_token)

    def create_pr_from_issue(
        self,
        repo_name: str,
        issue_number: int,
        branch_name: str,
        changes_summary: str,
        base_branch: str = "main",
    ) -> Dict[str, Any]:
        """
        Create a PR for an issue resolution.

        Args:
            repo_name: Repository name
            issue_number: Issue number being resolved
            branch_name: Branch with changes
            changes_summary: Summary of changes made
            base_branch: Target branch (default: main)

        Returns:
            PR data including number and URL
        """
        # Get issue details
        issue = self.github.get_issue(repo_name, issue_number)

        # Build PR title
        pr_title = f"[AI] Fix: {issue['title']}"

        # Build PR body
        pr_body = self._build_pr_body(issue, changes_summary)

        # Create PR as draft initially
        pr_data = self.github.create_pull_request(
            repo_name=repo_name,
            title=pr_title,
            body=pr_body,
            head=branch_name,
            base=base_branch,
            draft=True,
        )

        # Add labels
        self.github.add_labels(repo_name, pr_data["number"], ["ai-generated", "needs-review"])

        # Comment on original issue
        self.github.create_comment(
            repo_name,
            issue_number,
            f"🤖 Pull Request created: #{pr_data['number']}\n\nI've created a PR with the proposed solution. Please review when ready.",
        )

        return pr_data

    def _build_pr_body(self, issue: Dict[str, Any], changes_summary: str) -> str:
        """Build PR description."""
        body = f"""## 🤖 AI-Generated Solution

This Pull Request was automatically generated to resolve #{issue['number']}.

### 📋 Issue Summary
{issue.get('body', 'No description provided')[:500]}

### 🔧 Changes Made
{changes_summary}

### ✅ Checklist
- [x] Code generated by Claude Code
- [x] Tests included
- [ ] Reviewed by GitHub Copilot (pending)
- [ ] Approved by human (required)

### 🔍 Review Instructions
1. Check the generated code meets requirements
2. Verify tests pass
3. Review security implications
4. Approve or request changes

### ⚠️ Important
This code was generated by AI and requires human review before merging.

---

Resolves #{issue['number']}

🤖 Generated with [AI-Driven Issue Resolution System](https://github.com/ai-issue-resolver)
"""
        return body

    def mark_ready_for_review(self, repo_name: str, pr_number: int) -> None:
        """Mark PR as ready for review (remove draft status)."""
        # Note: PyGithub doesn't directly support changing draft status
        # This would need to use GraphQL API or gh CLI
        self.github.create_comment(
            repo_name,
            pr_number,
            "✅ Code generation and initial tests complete. Ready for review!",
        )

    def request_changes(
        self,
        repo_name: str,
        pr_number: int,
        reviewer: str,
        feedback: str,
    ) -> None:
        """Record change request from reviewer."""
        comment = f"""## 🔄 Changes Requested by @{reviewer}

{feedback}

I'll work on addressing these changes shortly.
"""
        self.github.create_comment(repo_name, pr_number, comment)

    def update_after_changes(
        self,
        repo_name: str,
        pr_number: int,
        changes_made: str,
    ) -> None:
        """Update PR after making requested changes."""
        comment = f"""## ✨ Changes Applied

{changes_made}

Please review the updates.
"""
        self.github.create_comment(repo_name, pr_number, comment)

    def get_pr_status(self, repo_name: str, pr_number: int) -> Dict[str, Any]:
        """
        Get comprehensive PR status.

        Returns status including reviews, comments, checks, etc.
        """
        pr = self.github.get_pull_request(repo_name, pr_number)
        reviews = self.github.get_pr_reviews(repo_name, pr_number)
        comments = self.github.get_pr_comments(repo_name, pr_number)

        # Determine review status
        latest_reviews = {}
        for review in reviews:
            user = review["user"]
            if user not in latest_reviews or review["submitted_at"] > latest_reviews[user]["submitted_at"]:
                latest_reviews[user] = review

        approved_count = sum(1 for r in latest_reviews.values() if r["state"] == "APPROVED")
        changes_requested_count = sum(1 for r in latest_reviews.values() if r["state"] == "CHANGES_REQUESTED")

        return {
            "pr": pr,
            "reviews": reviews,
            "comments": comments,
            "approved_count": approved_count,
            "changes_requested_count": changes_requested_count,
            "ready_to_merge": pr["mergeable"] and approved_count > 0 and changes_requested_count == 0,
        }

    def close_pr(
        self,
        repo_name: str,
        pr_number: int,
        reason: str,
    ) -> None:
        """Close PR with reason."""
        comment = f"""## ❌ Closing PR

**Reason**: {reason}

This PR has been automatically closed.
"""
        self.github.create_comment(repo_name, pr_number, comment)
        self.github.update_pull_request(repo_name, pr_number, state="closed")


# Example usage
if __name__ == "__main__":
    if len(sys.argv) < 4:
        print("Usage: python pr_manager.py <repo> <issue_number> <branch>")
        sys.exit(1)

    manager = PRManager()
    pr = manager.create_pr_from_issue(
        repo_name=sys.argv[1],
        issue_number=int(sys.argv[2]),
        branch_name=sys.argv[3],
        changes_summary="Auto-generated changes from AI",
    )

    print(f"PR created: #{pr['number']}")
    print(f"URL: {pr['url']}")
