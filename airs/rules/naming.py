#!/usr/bin/env python3
"""
Naming Rules Module

Enforces naming conventions for branches, commits, etc.
"""

import re
from typing import Dict, Any, Optional


class NamingRules:
    """Enforces naming conventions."""

    # Branch naming patterns
    BRANCH_PATTERNS = {
        "bot": r"^bot/issue-\d+-.+$",  # bot/issue-123-fix-validation
        "feature": r"^feature/.+$",
        "fix": r"^fix/.+$",
        "docs": r"^docs/.+$",
    }

    # Commit message pattern (Conventional Commits)
    COMMIT_PATTERN = r"^(feat|fix|docs|style|refactor|test|chore)(\(.+\))?: .{10,}$"

    @staticmethod
    def generate_branch_name(issue_number: int, issue_title: str) -> str:
        """
        Generate branch name from issue.

        Args:
            issue_number: Issue number
            issue_title: Issue title

        Returns:
            Branch name following convention
        """
        # Slugify title
        slug = issue_title.lower()
        slug = re.sub(r"[^\w\s-]", "", slug)  # Remove special chars
        slug = re.sub(r"[-\s]+", "-", slug)  # Normalize hyphens/spaces
        slug = slug[:50]  # Limit length
        slug = slug.strip("-")  # Remove trailing hyphens

        return f"bot/issue-{issue_number}-{slug}"

    @staticmethod
    def generate_commit_message(
        issue_number: int,
        issue_title: str,
        change_type: str = "fix",
        scope: Optional[str] = None,
    ) -> str:
        """
        Generate commit message following Conventional Commits.

        Args:
            issue_number: Issue number
            issue_title: Issue title
            change_type: Type (feat, fix, docs, etc.)
            scope: Optional scope

        Returns:
            Commit message
        """
        # Build commit title
        scope_part = f"({scope})" if scope else ""
        title = f"{change_type}{scope_part}: {issue_title}"

        # Build commit body
        body = f"""
AI-generated solution for issue #{issue_number}.

This commit was automatically generated by the AI-Driven Issue Resolution System.

Resolves #{issue_number}

Co-authored-by: ClaudeCode <claude@anthropic.com>
"""

        return f"{title}\n{body.strip()}"

    @staticmethod
    def validate_branch_name(branch_name: str) -> Dict[str, Any]:
        """
        Validate branch name against conventions.

        Args:
            branch_name: Branch name to validate

        Returns:
            Validation result
        """
        for branch_type, pattern in NamingRules.BRANCH_PATTERNS.items():
            if re.match(pattern, branch_name):
                return {
                    "valid": True,
                    "type": branch_type,
                    "message": f"Valid {branch_type} branch name",
                }

        return {
            "valid": False,
            "type": "unknown",
            "message": f"Branch name should match one of: {', '.join(NamingRules.BRANCH_PATTERNS.keys())}",
        }

    @staticmethod
    def validate_commit_message(message: str) -> Dict[str, Any]:
        """
        Validate commit message against Conventional Commits.

        Args:
            message: Commit message to validate

        Returns:
            Validation result
        """
        # Get first line
        first_line = message.split("\n")[0]

        if re.match(NamingRules.COMMIT_PATTERN, first_line):
            # Extract type
            match = re.match(r"^(\w+)", first_line)
            commit_type = match.group(1) if match else "unknown"

            return {"valid": True, "type": commit_type, "message": "Valid commit message"}

        return {
            "valid": False,
            "type": "unknown",
            "message": "Commit message should follow Conventional Commits format: type(scope): description",
        }


# Example usage
if __name__ == "__main__":
    rules = NamingRules()

    # Test branch name generation
    branch = rules.generate_branch_name(123, "Fix validation bug in user registration")
    print(f"Generated branch: {branch}")

    # Test commit message generation
    commit = rules.generate_commit_message(123, "Fix validation bug", "fix", "auth")
    print(f"\nGenerated commit:\n{commit}")

    # Test validation
    print(f"\nValidation: {rules.validate_branch_name(branch)}")
    print(f"Validation: {rules.validate_commit_message(commit.split(chr(10))[0])}")
