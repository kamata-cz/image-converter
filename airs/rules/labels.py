#!/usr/bin/env python3
"""
Label Manager Module

Manages GitHub labels for automation workflow.
"""

from typing import List, Dict, Any
from enum import Enum


class WorkflowLabel(Enum):
    """Standard workflow labels."""

    # Trigger labels
    AUTO_FIX = "auto-fix"  # Trigger automatic fixing
    AI_RESOLVABLE = "ai-resolvable"  # Issue can be resolved by AI

    # Status labels
    AI_ANALYZING = "ai-analyzing"  # AI is analyzing the issue
    AI_IMPLEMENTING = "ai-implementing"  # AI is implementing solution
    AI_GENERATED = "ai-generated"  # PR was generated by AI
    NEEDS_REVIEW = "needs-review"  # Needs review
    AI_REVIEWED = "ai-reviewed"  # AI review complete
    READY_FOR_HUMAN = "ready-for-human-review"  # Ready for human approval
    AI_FIXING = "ai-fixing"  # AI is applying fixes
    READY_TO_MERGE = "ready-to-merge"  # All checks passed, ready to merge

    # Problem labels
    TESTS_FAILING = "tests-failing"  # Tests are failing
    SIZE_EXCEEDED = "size-exceeded"  # Change too large
    SECURITY_RISK = "security-risk"  # Security concerns detected
    NEEDS_HUMAN = "needs-human-intervention"  # Requires human intervention

    # Quality labels
    HIGH_QUALITY = "high-quality"  # High quality code
    NEEDS_IMPROVEMENT = "needs-improvement"  # Quality issues

    # Priority labels
    PRIORITY_HIGH = "priority-high"
    PRIORITY_MEDIUM = "priority-medium"
    PRIORITY_LOW = "priority-low"


class LabelManager:
    """Manages labels for issues and PRs."""

    @staticmethod
    def should_auto_process(labels: List[str]) -> bool:
        """
        Check if issue should be auto-processed.

        Args:
            labels: List of label names

        Returns:
            True if should auto-process
        """
        trigger_labels = [WorkflowLabel.AUTO_FIX.value, WorkflowLabel.AI_RESOLVABLE.value]
        return any(label in labels for label in trigger_labels)

    @staticmethod
    def should_block(labels: List[str]) -> bool:
        """
        Check if processing should be blocked.

        Args:
            labels: List of label names

        Returns:
            True if should block
        """
        blocking_labels = [
            WorkflowLabel.NEEDS_HUMAN.value,
            WorkflowLabel.SECURITY_RISK.value,
            WorkflowLabel.SIZE_EXCEEDED.value,
        ]
        return any(label in labels for label in blocking_labels)

    @staticmethod
    def get_workflow_stage(labels: List[str]) -> str:
        """
        Determine current workflow stage from labels.

        Args:
            labels: List of label names

        Returns:
            Workflow stage name
        """
        # Check in order of workflow progression
        if WorkflowLabel.READY_TO_MERGE.value in labels:
            return "ready_to_merge"
        if WorkflowLabel.READY_FOR_HUMAN.value in labels:
            return "awaiting_human_review"
        if WorkflowLabel.AI_FIXING.value in labels:
            return "applying_fixes"
        if WorkflowLabel.AI_REVIEWED.value in labels:
            return "reviewed"
        if WorkflowLabel.AI_GENERATED.value in labels:
            return "pr_created"
        if WorkflowLabel.AI_IMPLEMENTING.value in labels:
            return "implementing"
        if WorkflowLabel.AI_ANALYZING.value in labels:
            return "analyzing"

        return "initial"

    @staticmethod
    def labels_for_stage(stage: str) -> List[str]:
        """
        Get labels to apply for a workflow stage.

        Args:
            stage: Workflow stage

        Returns:
            List of label names to apply
        """
        stage_labels = {
            "analyzing": [WorkflowLabel.AI_ANALYZING.value],
            "implementing": [WorkflowLabel.AI_IMPLEMENTING.value],
            "pr_created": [WorkflowLabel.AI_GENERATED.value, WorkflowLabel.NEEDS_REVIEW.value],
            "reviewed": [WorkflowLabel.AI_REVIEWED.value, WorkflowLabel.READY_FOR_HUMAN.value],
            "applying_fixes": [WorkflowLabel.AI_FIXING.value],
            "ready_to_merge": [WorkflowLabel.READY_TO_MERGE.value],
        }

        return stage_labels.get(stage, [])

    @staticmethod
    def labels_to_remove_for_stage(stage: str) -> List[str]:
        """
        Get labels to remove when entering a stage.

        Args:
            stage: Workflow stage

        Returns:
            List of label names to remove
        """
        # Remove previous stage labels
        stage_removals = {
            "implementing": [WorkflowLabel.AI_ANALYZING.value],
            "pr_created": [WorkflowLabel.AI_IMPLEMENTING.value],
            "reviewed": [WorkflowLabel.NEEDS_REVIEW.value],
            "applying_fixes": [WorkflowLabel.READY_FOR_HUMAN.value],
            "ready_to_merge": [WorkflowLabel.AI_FIXING.value, WorkflowLabel.NEEDS_REVIEW.value],
        }

        return stage_removals.get(stage, [])

    @staticmethod
    def format_label_summary(labels: List[str]) -> str:
        """Format labels for display."""
        if not labels:
            return "No labels"

        return ", ".join(f"`{label}`" for label in labels)


# Example usage
if __name__ == "__main__":
    manager = LabelManager()

    # Test auto-process detection
    test_labels = ["bug", "auto-fix", "priority-high"]
    print(f"Should auto-process: {manager.should_auto_process(test_labels)}")

    # Test stage detection
    stage_labels = ["ai-generated", "needs-review"]
    print(f"Current stage: {manager.get_workflow_stage(stage_labels)}")

    # Test stage progression
    for stage in ["analyzing", "implementing", "pr_created", "reviewed", "ready_to_merge"]:
        to_add = manager.labels_for_stage(stage)
        to_remove = manager.labels_to_remove_for_stage(stage)
        print(f"\nStage: {stage}")
        print(f"  Add: {to_add}")
        print(f"  Remove: {to_remove}")
