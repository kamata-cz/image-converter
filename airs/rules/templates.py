#!/usr/bin/env python3
"""
PR Template Module

Generates standardized PR descriptions.
"""

from typing import Dict, Any, List, Optional


class PRTemplate:
    """Generates PR descriptions following standard template."""

    @staticmethod
    def generate(
        issue_number: int,
        issue_title: str,
        changes_summary: str,
        files_changed: List[str],
        test_results: Optional[Dict[str, Any]] = None,
        warnings: Optional[List[str]] = None,
    ) -> str:
        """
        Generate PR description from template.

        Args:
            issue_number: Issue number
            issue_title: Issue title
            changes_summary: Summary of changes made
            files_changed: List of files changed
            test_results: Optional test results
            warnings: Optional warnings

        Returns:
            PR description
        """
        pr_body = f"""## 🤖 AI-Generated Solution

This Pull Request was automatically generated to resolve #{issue_number}.

### 📋 Issue Summary

**{issue_title}**

### 🔧 Changes Made

{changes_summary}

### 📁 Files Changed ({len(files_changed)})

"""

        # Add files (limit to 15)
        for file_path in files_changed[:15]:
            pr_body += f"- `{file_path}`\n"

        if len(files_changed) > 15:
            pr_body += f"- ... and {len(files_changed) - 15} more files\n"

        # Add test results if available
        if test_results:
            pr_body += "\n### 🧪 Test Results\n\n"
            if test_results.get("passed"):
                pr_body += f"✅ **All tests passed** ({test_results.get('total', 0)} tests)\n"
            else:
                failed = test_results.get("failed", 0)
                total = test_results.get("total", 0)
                pr_body += f"❌ **{failed}/{total} tests failed**\n"

        # Add warnings if any
        if warnings:
            pr_body += "\n### ⚠️ Warnings\n\n"
            for warning in warnings:
                pr_body += f"- {warning}\n"

        # Add checklist
        pr_body += """

### ✅ Automated Checks

- [x] Code generated by ClaudeCode
- [x] Code follows project conventions
- [x] Tests included
- [x] Security scan passed
- [ ] Reviewed by GitHub Copilot (in progress)
- [ ] Approved by human (required)

### 🔍 Review Instructions

**For AI Reviewer (Copilot):**
1. Check code quality and correctness
2. Verify test coverage
3. Identify potential bugs or security issues
4. Ensure code follows best practices

**For Human Reviewer:**
1. Verify the solution addresses the issue requirements
2. Check for business logic correctness
3. Review security implications
4. Approve or request changes

### 📊 Impact Analysis

- **Complexity**: Auto-detected based on changes
- **Risk Level**: Low (AI-generated with guardrails)
- **Rollback**: Can be reverted cleanly if needed

### ⚠️ Important Notes

This code was generated by AI and has passed automated checks, but **requires human review** before merging.

**Changes have been validated against:**
- Path restrictions
- Size limits
- Secret detection
- Dangerous operation detection
- Code quality standards

### 🔄 Iterative Fixes

If changes are requested during review, AI will automatically attempt to address them (up to 3 iterations).

---

Resolves #{issue_number}

🤖 Generated with [AI-Driven Issue Resolution System](https://github.com/ai-airs)

Co-authored-by: ClaudeCode <claude@anthropic.com>
"""

        return pr_body

    @staticmethod
    def generate_fix_update(
        iteration: int,
        feedback_summary: str,
        changes_made: str,
    ) -> str:
        """
        Generate update comment for iterative fixes.

        Args:
            iteration: Fix iteration number
            feedback_summary: Summary of review feedback
            changes_made: Description of changes made

        Returns:
            Update comment
        """
        comment = f"""## 🔄 Iteration {iteration}: Fixes Applied

### 📝 Review Feedback

{feedback_summary}

### ✨ Changes Made

{changes_made}

### ✅ Status

Fixes have been applied and pushed. Please review the updates.

---

*Automated fix iteration {iteration}/3*
"""

        return comment

    @staticmethod
    def generate_escalation_comment(reason: str, details: str) -> str:
        """
        Generate comment for human escalation.

        Args:
            reason: Escalation reason
            details: Additional details

        Returns:
            Escalation comment
        """
        return f"""## 👨‍💻 Human Intervention Required

**Reason**: {reason}

### Details

{details}

### Next Steps

A human developer needs to review and complete this change manually.

**What went wrong:**
- AI attempted automatic resolution but encountered limitations
- This change requires human judgment or expertise

**Recommended Actions:**
1. Review the attempted changes above
2. Complete the implementation manually
3. Update this PR or create a new one
4. Close this PR if no longer needed

---

⚠️ *Automated processing halted - human review required*
"""


# Example usage
if __name__ == "__main__":
    template = PRTemplate()

    pr_desc = template.generate(
        issue_number=123,
        issue_title="Fix validation bug in user registration",
        changes_summary="Added email format validation and password strength checks",
        files_changed=["src/auth/validation.py", "tests/test_validation.py"],
        test_results={"passed": True, "total": 15, "failed": 0},
        warnings=["File src/auth/validation.py has 450 lines (close to 500 limit)"],
    )

    print(pr_desc)
