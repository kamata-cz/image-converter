#!/usr/bin/env python3
"""
Metrics Reporter Module

Generates reports from collected metrics.
"""

from typing import Dict, Any
from datetime import datetime, timedelta
from .collector import MetricsCollector, SystemMetrics


class MetricsReporter:
    """Generates reports from metrics."""

    def __init__(self, collector: MetricsCollector):
        """
        Initialize reporter.

        Args:
            collector: MetricsCollector instance
        """
        self.collector = collector

    def generate_summary(self, days: int = 30) -> str:
        """
        Generate summary report for last N days.

        Args:
            days: Number of days to include

        Returns:
            Markdown-formatted report
        """
        end_date = datetime.now()
        start_date = end_date - timedelta(days=days)

        metrics = self.collector.load_period_metrics(
            start_date.strftime("%Y-%m-%d"),
            end_date.strftime("%Y-%m-%d"),
        )

        report = f"""# AI-Driven Issue Resolution System - {days}-Day Report

**Period**: {metrics.period_start} to {metrics.period_end}

## 📊 Summary Statistics

### Volume
- **Total Issues**: {metrics.total_issues}
- **Auto-Resolved**: {metrics.auto_resolved} ({metrics.success_rate*100:.1f}%)
- **Human Escalated**: {metrics.human_escalated}
- **Failed**: {metrics.failed}

### Success Rates
- **Overall Success Rate**: {metrics.success_rate*100:.1f}%
- **First-Pass Success Rate**: {metrics.first_pass_success_rate*100:.1f}%

### Performance
- **Average Total Time**: {metrics.avg_total_time/60:.1f} minutes
- **Average Iterations**: {metrics.avg_iterations:.1f}
- **Average Files Changed**: {metrics.avg_files_changed:.1f}

## 📈 Trends

"""

        # Add interpretation
        if metrics.success_rate >= 0.8:
            report += "✅ **Excellent performance** - System is resolving most issues successfully.\n\n"
        elif metrics.success_rate >= 0.6:
            report += "⚠️ **Good performance** - Some improvement opportunities exist.\n\n"
        else:
            report += "❌ **Needs attention** - Success rate is below target.\n\n"

        if metrics.first_pass_success_rate >= 0.7:
            report += "✅ **High code quality** - Most solutions work on first attempt.\n\n"
        else:
            report += "⚠️ **Review quality** - Many solutions require iterations.\n\n"

        if metrics.avg_iterations < 1.5:
            report += "✅ **Efficient iteration** - Quick convergence to solution.\n\n"
        else:
            report += "⚠️ **High iteration count** - May need better initial prompts.\n\n"

        report += """## 🎯 Recommendations

"""

        # Generate recommendations based on metrics
        if metrics.success_rate < 0.7:
            report += "1. **Improve Success Rate**: Review failed issues to identify patterns\n"

        if metrics.avg_iterations > 2.0:
            report += "2. **Reduce Iterations**: Improve AI prompts and context building\n"

        if metrics.human_escalated > metrics.total_issues * 0.3:
            report += "3. **Reduce Escalations**: Expand AI capabilities or improve guardrails\n"

        report += """
## 📝 Next Steps

- Continue monitoring key metrics
- Investigate outliers and failures
- Refine AI prompts based on common patterns
- Adjust guardrails as needed

---

*Generated by AI-Driven Issue Resolution System*
"""

        return report

    def generate_issue_report(self, issue_number: int) -> str:
        """
        Generate detailed report for a single issue.

        Args:
            issue_number: Issue number

        Returns:
            Markdown-formatted report
        """
        # This would load specific issue metrics
        report = f"""# Issue #{issue_number} - Resolution Report

## Timeline

- **Started**: [timestamp]
- **Completed**: [timestamp]
- **Total Time**: [duration]

## Stages

- **Analysis**: [duration]
- **Implementation**: [duration]
- **Review**: [duration]

## Changes

- **Files Modified**: [count]
- **Lines Added**: [count]
- **Lines Removed**: [count]
- **Tests Added**: [count]

## Review

- **Iterations**: [count]
- **Copilot Approved**: [yes/no]
- **Human Approved**: [yes/no]

## Outcome

- **Success**: [yes/no]
- **PR Created**: [number]

---

*Detailed metrics for auditing and analysis*
"""

        return report


# Example usage
if __name__ == "__main__":
    collector = MetricsCollector()
    reporter = MetricsReporter(collector)

    # Generate 30-day summary
    summary = reporter.generate_summary(days=30)
    print(summary)
