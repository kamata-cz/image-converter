"""段階 5 の費用表を計算する（2026-11-04 の調査値。出典は docs/05-research/raw/）。"""
# 運用費の案: (名前, 初年度の円, 2 年目以降の年額の円, 中身)
plans = [
    ("A 0 円", 0, 0, "GitHub Pages＋GoatCounter（無料）"),
    ("B .com ドメイン", 790, 2283, "A＋独自ドメイン .com（バリュードメインの登録 790 円・更新 2,283 円）"),
    ("C .jp ドメイン", 1485, 3889, "A＋独自ドメイン .jp（同 登録 1,485 円・更新 3,889 円）"),
]
print("| 案 | 初年度 | 2 年目以降（年） | 3 年の合計 | 中身 |")
print("|---|---:|---:|---:|---|")
for name, y1, yn, what in plans:
    print(f"| {name} | {y1:,} 円 | {yn:,} 円 | {y1 + yn * 2:,} 円 | {what} |")

# 寄付の手取り（codex 調査の式。OFUSE は親が未照合）
print("\n| 寄付の受け取り方 | 1,000 円の手取り（出金前） | 出金 1 回の手数料 | 1,000 円×10 件をまとめて 1 回出金したときの手取り |")
print("|---|---:|---:|---:|")
rows = [("OFUSE 単発（16%）", lambda a: a * 0.84, 275),
        ("Ko-fi 無料＋PayPal 国内商用（3.6%＋40 円）", lambda a: a - a * 0.036 - 40, 250)]
for name, f, fee in rows:
    one = f(1000)
    print(f"| {name} | {one:,.0f} 円 | {fee} 円 | {one * 10 - fee:,.0f} 円 |")
